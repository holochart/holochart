# %% [markdown]
# ## Calendar time with a missing observation
# Generate timezone-aware UTC timestamps locally. Explicit ISO strings work without Plotly's
# optional date encoder. Keep the timestamp whose reading is missing; do not drop only its y row.
# The axis displays dates while the y title keeps the measurement's unit visible.

# %% Datetimes and data
from datetime import datetime, timedelta, timezone

start = datetime(2026, 1, 1, tzinfo=timezone.utc)
timestamps = [(start + timedelta(hours=index)).isoformat() for index in range(6)]
readings = [18.1, 18.8, None, 20.0, 19.4, 18.7]
assert len(timestamps) == len(readings)
calendar_figure = {
    "data": [{"type": "scatter", "mode": "lines+markers", "name": "Sensor",
              "x": timestamps, "y": readings, "connectgaps": False}],
    "layout": {"title": {"text": "UTC sensor readings"},
               "xaxis": {"type": "date", "title": {"text": "Time (UTC)"}},
               "yaxis": {"title": {"text": "Temperature (°C)"}}},
}

# %% Display calendar time
if "calendar_chart" in globals():
    calendar_chart.close()
calendar_chart = HolochartWidget(calendar_figure, height=360)
assert calendar_chart.figure["data"][0]["y"][2] is None
display(calendar_chart)
