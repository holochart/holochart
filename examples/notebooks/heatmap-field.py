# %% Imports
import numpy as np
from IPython.display import display
from holochart import HolochartWidget

# %% Data and figure
x = np.linspace(-3, 3, 60)
y = np.linspace(-2, 2, 40)
xx, yy = np.meshgrid(x, y)
z = (np.exp(-((xx - 1) ** 2 + (yy - 0.5) ** 2))
     + 0.8 * np.exp(-((xx + 1.4) ** 2 + (yy + 0.6) ** 2) / 0.6)
     - 0.5 * np.exp(-((xx + 0.2) ** 2 + (yy - 1.2) ** 2) / 0.3))
figure = {
    "data": [{"type": "heatmap", "x": x, "y": y, "z": z,
              "colorbar": {"title": {"text": "intensity"}}}],
    "layout": {"title": {"text": "Field intensity"},
               "xaxis": {"title": {"text": "x (mm)"}}, "yaxis": {"title": {"text": "y (mm)"}}},
}

# %% Display
if "field_chart" in globals():
    field_chart.close()
field_chart = HolochartWidget(figure, height=400)
display(field_chart)

