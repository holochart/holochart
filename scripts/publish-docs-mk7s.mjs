#!/usr/bin/env node
// Build the Holochart docs and publish them into the mk7s.dev site at /holochart/.
//
// mk7s.dev is a Vite site deployed to the Cloudflare Pages project `mk7s`. Its `public/` folder is
// copied verbatim into `dist/`, so the docs go to `<mk7s>/public/holochart/` (VitePress already
// builds with `base: '/holochart/'`). Cloudflare Pages only reads the root `_headers` file, so the
// docs' header rules are merged into `<mk7s>/public/_headers` inside a managed block.
//
// Usage (from the holochart repo root):
//   node scripts/publish-docs-mk7s.mjs                  # build docs + copy into ../mk7s
//   node scripts/publish-docs-mk7s.mjs --deploy         # ...then build mk7s and deploy to production
//   node scripts/publish-docs-mk7s.mjs --deploy --branch preview   # deploy a preview instead
//
// Options: --mk7s <dir> (default ../mk7s), --skip-build (reuse the last docs build),
//          --deploy, --branch <name> (Pages branch; default: production).
// Deploying needs `npx wrangler login` once per machine (see the mk7s README).
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { parseArgs } from 'node:util';

const { values: args } = parseArgs({
  options: {
    mk7s: { type: 'string' },
    'skip-build': { type: 'boolean', default: false },
    deploy: { type: 'boolean', default: false },
    branch: { type: 'string' },
  },
});

const ROOT = path.resolve(import.meta.dirname, '..');
const MK7S = path.resolve(ROOT, args.mk7s ?? '../mk7s');
const DOCS_DIST = path.join(ROOT, 'apps/docs/.vitepress/dist');
const TARGET = path.join(MK7S, 'public/holochart');
const BEGIN =
  '# BEGIN holochart (generated by holochart/scripts/publish-docs-mk7s.mjs; do not edit)';
const END = '# END holochart';
const REDIRECT = '/holochart /holochart/ 308';

function fail(message) {
  console.error(`publish-docs-mk7s: ${message}`);
  process.exit(1);
}

function run(command, commandArgs, cwd) {
  console.log(`\n$ ${command} ${commandArgs.join(' ')}   (in ${cwd})`);
  const result = spawnSync(command, commandArgs, { cwd, stdio: 'inherit' });
  if (result.status !== 0) fail(`${command} ${commandArgs.join(' ')} failed`);
}

// Sanity checks: never write into the wrong folder.
const mk7sPackage = path.join(MK7S, 'package.json');
if (!existsSync(mk7sPackage) || JSON.parse(readFileSync(mk7sPackage, 'utf8')).name !== 'mk7s') {
  fail(`${MK7S} is not the mk7s site (expected a package.json named "mk7s")`);
}

// 1. Build the docs (regenerates the schema reference and API pages first).
if (!args['skip-build']) run('pnpm', ['--filter', '@mk7s/holochart-docs', 'build'], ROOT);
if (!existsSync(path.join(DOCS_DIST, 'index.html'))) fail(`no docs build at ${DOCS_DIST}`);

// 2. Replace <mk7s>/public/holochart with the fresh build (minus _headers, merged below).
rmSync(TARGET, { recursive: true, force: true });
cpSync(DOCS_DIST, TARGET, {
  recursive: true,
  filter: (src) => path.relative(DOCS_DIST, src) !== '_headers',
});
console.log(`\nCopied docs build → ${path.relative(ROOT, TARGET)}`);

// 3. Merge the docs' header rules (already scoped to /holochart/*) into the root _headers.
const headersPath = path.join(MK7S, 'public/_headers');
const docsHeaders = existsSync(path.join(DOCS_DIST, '_headers'))
  ? readFileSync(path.join(DOCS_DIST, '_headers'), 'utf8').trim()
  : '';
let headers = existsSync(headersPath) ? readFileSync(headersPath, 'utf8') : '';
const start = headers.indexOf(BEGIN);
const stop = headers.indexOf(END);
if (start !== -1 && stop > start)
  headers = headers.slice(0, start) + headers.slice(stop + END.length);
headers = headers.trim();
const block = docsHeaders ? `${BEGIN}\n${docsHeaders}\n${END}` : '';
writeFileSync(headersPath, [headers, block].filter(Boolean).join('\n\n') + '\n');

// 4. /holochart → /holochart/ (Pages; the Vite dev/preview servers do the same in vite.config.js).
const redirectsPath = path.join(MK7S, 'public/_redirects');
const redirects = existsSync(redirectsPath) ? readFileSync(redirectsPath, 'utf8') : '';
if (!redirects.split('\n').some((line) => line.trim() === REDIRECT)) {
  writeFileSync(redirectsPath, `${redirects.trimEnd()}\n${REDIRECT}\n`.trimStart());
}
console.log('Updated public/_headers and public/_redirects');

// 5. Optionally build the whole mk7s site and deploy it to Cloudflare Pages.
if (args.deploy) {
  run('npm', ['run', 'build'], MK7S);
  if (!existsSync(path.join(MK7S, 'dist/holochart/index.html'))) {
    fail('mk7s build has no dist/holochart/index.html');
  }
  const deployArgs = ['wrangler', 'pages', 'deploy', 'dist', '--project-name', 'mk7s'];
  if (args.branch) deployArgs.push('--branch', args.branch);
  run('npx', deployArgs, MK7S);
} else {
  console.log(
    '\nNot deployed. Preview with `npm run build && npm run preview` in the mk7s folder, then run' +
      ' this script with --deploy (or `npx wrangler pages deploy dist --project-name mk7s` there).',
  );
}
